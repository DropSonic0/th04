#ifndef TH04_SHARED_HARDWARE_GAIJI_HPP
#define TH04_SHARED_HARDWARE_GAIJI_HPP

// TH04 gaiji code points used by the score-registration keyboard. The
// accepted 51-byte MAINE alphabet places these controls in its final row.
enum {
    g_EMPTY = 0x02,
    gs_SPACE = 0xCD,
    gs_ARROW_LEFT = 0xCE,
    gs_ARROW_RIGHT = 0xCF,
};

#endif
